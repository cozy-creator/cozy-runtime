#!/usr/bin/env python
"""The wire fence, checked from the vendored bindings alone — no network, no sibling repo.

WHAT THIS REFUSES. A vendored `cozy.worker.v1` binding that is not the schema it claims to
be. That is the whole of #530-A1: `WIRE_MINOR` fenced nothing, because a version constant
can agree while the bytes disagree — the protocol sat at rev 2 while two vendored copies sat
revisions behind and all three declared minor 0.

WHY IT CAN RUN HERE AT ALL. The identity is DERIVED, not declared: `worker_pb2.py` embeds
its own `FileDescriptorProto`, so the schema digest is recomputable from the bindings this
repo actually ships, with the same canonicalizer every other digest in this contract uses.
A stale copy cannot spell the digest without BEING the schema it names.

WHAT IT DOES NOT COVER, said out loud. It fences the SCHEMA, not the generated FILES: a
correct schema regenerated by a different protoc, or a hand-edited grpc stub, digests the
same. That is `worker-protocol/scripts/vendored-diff.sh`, which needs the protocol repo and
runs in CI's `drift` job the moment a read credential for it exists. This step is what fires
in the meantime, and it fires on every push rather than waiting behind anything.

    uv run python checks/wire_schema.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from cozy.worker.v1 import wire_identity  # noqa: E402
from cozy_runtime.protocol import documents  # noqa: E402

#: THE PIN. worker-protocol `315fdde`, `WIRE_SCHEMA_REV` 6, and the digest its `SCHEMA_REVS`
#: ledger registers for that rev. Written here as a LITERAL on purpose: comparing the derived
#: digest only against `wire_identity.SCHEMA_DIGEST` proves the copy is self-consistent, and
#: a wholesale re-vendor of some other schema would be self-consistent too. The literal is
#: what says WHICH schema this repo is a consumer of, and moving it is the deliberate act of
#: adopting a new protocol rev.
PROTOCOL_SHA = "315fdde7cf22568b640d2d1184d4cae9909a6b2e"
WIRE_SCHEMA_REV = 6
SCHEMA_DIGEST = "sha256:b5cd4430ef6d8b17e4d6d4126cd68ad132e069cae03339deb1476d928e1b3309"


def main() -> int:
    document = documents.wire_schema_document()
    derived = "sha256:" + documents.digest_of(document).hex()
    failures: list[str] = []

    if wire_identity.WIRE_SCHEMA_REV != WIRE_SCHEMA_REV:
        failures.append(
            f"the vendored binding declares schema rev {wire_identity.WIRE_SCHEMA_REV} and "
            f"this repo is pinned to rev {WIRE_SCHEMA_REV}"
        )
    if derived != wire_identity.SCHEMA_DIGEST:
        failures.append(
            f"DECLARED vs DERIVED: wire_identity.py says {wire_identity.SCHEMA_DIGEST} and "
            f"the descriptor in worker_pb2.py digests to {derived} — regen.sh wrote a "
            "constant for a schema this copy is not"
        )
    if derived != SCHEMA_DIGEST:
        failures.append(
            f"the vendored schema digests to {derived} and this repo is pinned to "
            f"{SCHEMA_DIGEST} (worker-protocol {PROTOCOL_SHA[:7]}, rev {WIRE_SCHEMA_REV}) — "
            "adopting a new protocol rev means moving the pin in this file too"
        )

    if failures:
        print("wire fence REFUSED:", file=sys.stderr)
        for row in failures:
            print(f"  - {row}", file=sys.stderr)
        print(
            "\nRegenerate: run scripts/regen.sh in worker-protocol, copy gen/python/cozy "
            "over src/cozy, and move PROTOCOL_SHA/SCHEMA_DIGEST here.",
            file=sys.stderr,
        )
        return 1

    print(
        f"wire fence green — cozy.worker.v1 schema rev {WIRE_SCHEMA_REV} "
        f"(wire_minor {wire_identity.WIRE_MINOR}), {len(document)} B of canonical "
        f"WireSchema/1 digesting to {derived}, derived from the vendored descriptor and "
        f"pinned to worker-protocol {PROTOCOL_SHA[:7]}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
