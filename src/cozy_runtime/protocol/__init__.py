"""`cozy.worker.v1` — the wire contract, COPIED OUT of worker-protocol and owned here.

The generated bindings live at `src/cozy/worker/v1/` under the proto package path their own
import lines name, and they are protoc's output BYTE-FOR-BYTE. The old copy was flattened
into this package with one hand edit to the stub's import line; that edit is gone, because a
copy with an edit in it cannot be byte-compared against its source, and byte-comparison is
the drift gate (`worker-protocol/scripts/vendored-diff.sh`, #536d). The package is a PEP 420
namespace package — no `__init__.py` anywhere under `cozy/` — so nothing has to be
maintained beside the generated bytes.

This module is the consumer-owned half: it re-exports the bindings under the name the rest
of the tree already imports, and it carries the wire identity read from the GENERATED
`wire_identity.py` rather than declared here. `WIRE_MINOR` used to be a hand-written constant
in this file — a number that can agree while the bytes disagree, which is precisely what
#530-A1 retired. It is now whatever regen.sh wrote, beside the two facts that actually fence:

  * `WIRE_SCHEMA_REV` — which SHAPE this is, an ordinal for humans and diagnostics;
  * `SCHEMA_DIGEST` — THE FENCE: sha256 of the canonical `cozy.worker.v1.WireSchema/1`
    document, DERIVED from the descriptor. It rides Claim and ClaimAck and is checked before
    any other body field; absence IS the stale signal, because a pre-rev-2 binding cannot
    spell the field at all.

`documents.py` is NOT generated: it is the proto -> canonical-document mapping (the digest
plane), written against `internal/canonical.py`'s writer.

Refresh procedure: run `scripts/regen.sh` in worker-protocol, copy `gen/python/cozy` over
`src/cozy`, and prove it with `scripts/vendored-diff.sh <cozy-runtime>/src` — which is what
this repo's CI `drift` job runs.
"""

