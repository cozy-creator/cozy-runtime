"""Pure generation of ordinary typed caller code from a PackageInterface."""

from __future__ import annotations

import msgspec

from cozy_runtime.author._errors import ConformanceError
from cozy_runtime.internal import package_interface
from cozy_runtime.internal.canonical import Json
from cozy_runtime.internal.invocable_interface import Invocable
from cozy_runtime.internal.package_interface import CallableDoc


def generate(interface: bytes, distribution: str) -> str:
    """Generate a lightweight module from one actual canonical package interface."""
    body = package_interface.read_bytes(interface, source="call references")
    document = package_interface.parse(interface, source="call references")
    entries = [
        (entry, entry.invocable)
        for entry in document.entrypoints
        if entry.invocable is not msgspec.UNSET and not entry.internal
    ]
    if not entries:
        raise ConformanceError(
            "package declares no public callable exports", code="interface_exports_absent"
        )
    return _module(distribution, entries, body)


def _module(
    distribution: str, entries: list[tuple[CallableDoc, Invocable]], body: dict[str, Json]
) -> str:
    imports = [
        "# Generated by cozy-runtime calls from the locked package interface. Do not edit.",
        "from __future__ import annotations",
        "from typing import Annotated, Any, Literal",
        "from enum import Enum",
        "import msgspec",
        "from cozy_runtime.fields import "
        "FileBound, AudioPreparation, ImagePreparation, VideoPreparation",
        "from cozy_runtime.media import "
        "Files, ImageFile, AudioFile, VideoFile, File, Tree, Latents",
        "from cozy_runtime.author import ModelArtifact, ModelChoice, Seed",
        "from cozy_runtime.fields import AspectRatio, Audio, Image, Pickup, Prompt, Video",
        "from cozy_runtime.author import Operation",
        "",
    ]
    declarations: dict[str, tuple[bytes, str]] = {}
    functions: list[str] = []
    exports: set[str] = set()
    for entry, metadata in sorted(entries, key=lambda item: item[1].export):
        defaults, names, enums = metadata.defaults, metadata.type_names, metadata.enum_members

        def struct(
            node: Json,
            path: str,
            tag_field: str | None = None,
            *,
            base: str = "msgspec.Struct",
            names: dict[str, str] = names,
            defaults: dict[str, object] = defaults,
        ) -> str:
            """A struct's class; open wire types: a callee may add result fields a caller does
            not read yet."""
            name = names[path]
            if name.startswith("__cozy_") or name in exports:
                raise ConformanceError(
                    "interface type collides with a generated export",
                    code="interface_name_conflict",
                )
            options = ["kw_only=True", "frozen=True"]
            if "tag" in node:
                options += [
                    "tag=" + repr(node["tag"]),
                    "tag_field=" + repr(node.get("tag_field", tag_field or "type")),
                ]
            fields: list[str] = []
            for field in node["fields"]:
                field_path = path + "/" + field["name"]
                annotation = expression(field["type"], field_path)
                if constraints := field.get("constraints"):
                    meta = f"msgspec.Meta({_keywords(constraints)})"
                    members = (
                        field["type"].get("union", []) if isinstance(field["type"], dict) else []
                    )
                    if "null" in members and len(members) == 2:
                        # An optional value's bounds are its value's: `Annotated[T, ...] | None`.
                        at = 1 - members.index("null")
                        value = expression(members[at], f"{field_path}/union/{at}")
                        annotation = f"Annotated[{value}, {meta}] | None"
                    else:
                        annotation = f"Annotated[{annotation}, {meta}]"
                declared = field.get("asset_bound", {})
                bound = {
                    name: limit
                    for name, limit in declared.items()
                    if name in package_interface.ASSET_BOUND_KEYS
                }
                if bound:
                    annotation = f"Annotated[{annotation}, FileBound({_keywords(bound)})]"
                if (marker := _preparation(declared.get("prepare"))) is not None:
                    annotation = f"Annotated[{annotation}, {marker}]"
                default = ""
                if field_path in defaults:
                    default_value = defaults[field_path]
                    rendered = literal(field["type"], field_path, default_value)
                    default = (
                        f" = msgspec.field(default_factory={type(default_value).__name__})"
                        if default_value == [] or default_value == {}
                        else f" = msgspec.field(default_factory=lambda: {rendered})"
                        if isinstance(default_value, list)
                        else " = " + rendered
                    )
                fields.append(f"    {field['name']}: {annotation}{default}")
            source = (
                "class "
                + name
                + "("
                + base
                + ", "
                + ", ".join(options)
                + "):\n"
                + "\n".join(fields or ["    pass"])
                + "\n"
            )
            _declare(declarations, name, source)
            return name

        def expression(
            node: Json,
            path: str,
            tag_field: str | None = None,
            *,
            names: dict[str, str] = names,
            defaults: dict[str, object] = defaults,
            enums: dict[str, tuple[str, ...]] = enums,
        ) -> str:
            if isinstance(node, str):
                return {
                    "str": "str",
                    "int": "int",
                    "float": "float",
                    "bool": "bool",
                    "null": "None",
                }[node]
            if "media" in node:
                media = _MEDIA[node["media"]]
                return struct(node, path, tag_field, base=media) if node.get("fields") else media
            if "pickup" in node:
                return struct(node["pickup"], path, tag_field, base="Pickup")
            if "prompt" in node:
                kinds = [_MEDIA[kind] for kind in node["prompt"]]
                return "Prompt" if len(kinds) == len(_MEDIA) else f"Prompt[{' | '.join(kinds)}]"
            if "fields" in node:
                return struct(node, path, tag_field)
            if "literal" in node:
                if path in enums:
                    name = names[path]
                    rows = [
                        f"    {member} = {value!r}"
                        for member, value in zip(enums[path], node["literal"], strict=True)
                    ]
                    _declare(declarations, name, f"class {name}(Enum):\n" + "\n".join(rows) + "\n")
                    return name
                return "Literal[" + ", ".join(repr(value) for value in node["literal"]) + "]"
            if "list" in node:
                return "list[" + expression(node["list"], path + "/[]") + "]"
            if "map" in node:
                key = expression(node["map"]["key"], path + "/map/key")
                value = expression(node["map"]["value"], path + "/map/value")
                return f"dict[{key}, {value}]"
            if "tuple" in node:
                return (
                    "tuple["
                    + ", ".join(
                        expression(member, path + f"/tuple/{index}")
                        for index, member in enumerate(node["tuple"])
                    )
                    + "]"
                )
            if "union" in node:
                return " | ".join(
                    expression(member, path + f"/union/{index}", node.get("tag_field"))
                    for index, member in enumerate(node["union"])
                )
            if "asset" in node:
                return {
                    "image": "ImageFile",
                    "audio": "AudioFile",
                    "video": "VideoFile",
                    "file": "File",
                    "latents": "Latents",
                }[node["asset"]]
            if node.get("input") == "tree":
                return "Tree"
            if node.get("input") == "aspect_ratio":
                return "AspectRatio"
            if node.get("input") == "seed":
                return "Seed"
            if node.get("input") == "model":
                return "ModelArtifact"
            if node.get("opaque") == "Any":
                return "Any"
            raise ConformanceError(
                "interface schema has no portable Python type", code="interface_type"
            )

        def literal(
            node: Json,
            path: str,
            value: object,
            *,
            names: dict[str, str] = names,
            enums: dict[str, tuple[str, ...]] = enums,
        ) -> str:
            if path in enums:
                return names[path] + "." + enums[path][int(node["literal"].index(value))]
            if isinstance(node, dict) and isinstance(value, dict) and "prompt" in node:
                if value.get("references"):
                    raise ConformanceError("a default prompt has references", code="interface_type")
                arguments = ", ".join(
                    f"{key}={item!r}" for key, item in value.items() if key != "references"
                )
                return f"Prompt({arguments})"
            if isinstance(node, dict) and isinstance(value, dict) and "fields" in node:
                members = {field["name"]: field["type"] for field in node["fields"]}
                arguments = ", ".join(
                    f"{key}={literal(members[key], path + '/' + key, item)}"
                    for key, item in value.items()
                )
                return f"{names[path]}({arguments})"
            if isinstance(node, dict) and isinstance(value, list) and "list" in node:
                return (
                    "["
                    + ", ".join(literal(node["list"], path + "/[]", item) for item in value)
                    + "]"
                )
            return repr(value)

        assets_parameter = "" if entry.assets is msgspec.UNSET else entry.assets.parameter
        wire_request = "None"
        if assets_parameter:
            assert isinstance(entry.request, dict)
            request_fields = entry.request["fields"]
            assert isinstance(request_fields, list)
            payload = {
                **entry.request,
                "fields": [
                    field
                    for field in request_fields
                    if isinstance(field, dict) and field["name"] != assets_parameter
                ],
            }
            request_name = expression(payload, "request")
            original_name = names["request"]
            names["request"] = f"_{metadata.export}WireRequest"
            wire_request = struct(
                {
                    **entry.request,
                    "fields": [
                        field
                        for field in request_fields
                        if isinstance(field, dict) and field["name"] == assets_parameter
                    ],
                },
                "request",
                base=request_name,
            )
            names["request"] = original_name
        else:
            request_name = expression(entry.request, "request")
        result_name = expression(entry.result, "result")
        export = metadata.export
        if export in exports or export in declarations:
            raise ConformanceError(
                "interface repeats a Python export", code="interface_name_conflict"
            )
        exports.add(export)
        model_names = tuple(slot.parameter for slot in entry.models)
        declaration = package_interface.descriptor_id(body, entry.name)
        functions.append(
            f"{export}: Operation[{request_name}, {result_name}] = Operation(\n"
            f"    distribution={distribution!r}, module={metadata.module!r}, export={export!r},\n"
            f"    declaration={declaration!r}, request={request_name}, result={result_name},\n"
            f"    models={model_names!r}, assets_parameter={assets_parameter!r},\n"
            f"    wire_request={wire_request},\n)\n"
        )
    return "\n".join(imports + [item[1] for item in declarations.values()] + functions + [""])


_MEDIA = {"image": "Image", "video": "Video", "audio": "Audio"}


def _preparation(declared: object) -> str | None:
    """A known preparation profile as its marker spelling, from its grammar members only;
    an unknown profile is dropped."""
    if declared is None or declared is msgspec.UNSET:
        return None
    known = package_interface.preparation_members(declared)
    if known is None:
        return None
    marker, members = known
    return f"{marker.__name__}({_keywords(members)})"


def _declare(declarations: dict[str, tuple[bytes, str]], name: str, source: str) -> None:
    encoded = source.encode()
    if name in declarations and declarations[name][0] != encoded:
        raise ConformanceError(
            "interface types share a name but differ in meaning", code="interface_name_conflict"
        )
    declarations[name] = (encoded, source)


def _keywords(values: dict[str, object]) -> str:
    return ", ".join(
        f"{key}={tuple(value) if key == 'media_types' and isinstance(value, list) else value!r}"
        for key, value in values.items()
    )
