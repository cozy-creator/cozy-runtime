"""Measured numerical platform identity, independent of a caller's code and custody."""

from __future__ import annotations

import csv
import hashlib
import importlib.metadata
import io
import json
import platform
import subprocess
import sys
from collections.abc import Mapping
from pathlib import Path, PurePosixPath

from cozy_runtime import canonical_json
from cozy_runtime.internal.base_observation import Observation, protected_distribution
from cozy_runtime.internal.hostfacts import HostFacts


class NumericalEnvironmentRefusal(Exception):
    pass


def distribution_records(base: Observation) -> dict[str, dict[str, str]]:
    """Read the current interpreter's immutable protected distribution records."""
    return _installed_records(
        {name: version for name, version in base.distributions if protected_distribution(name)}
    )


def _prepared_distributions(
    base: Observation, python: Path
) -> tuple[dict[str, dict[str, str]], str]:
    expected = {
        name: version for name, version in base.distributions if protected_distribution(name)
    }
    result = subprocess.run(
        [str(python), "-I", "-m", "cozy_runtime.internal.numerical_environment"],
        input=json.dumps(expected),
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode or len(result.stdout) > 64 << 10:
        raise NumericalEnvironmentRefusal("prepared interpreter numerical identity is unproven")
    value = json.loads(result.stdout)
    if not isinstance(value, dict) or set(value) != {"records", "python_version"}:
        raise NumericalEnvironmentRefusal("prepared interpreter numerical identity is malformed")
    records, version = value["records"], value["python_version"]
    if (
        not isinstance(version, str)
        or "cp" + "".join(version.split(".")[:2]) != base.python_abi
        or not isinstance(records, dict)
        or set(records) != set(expected)
        or any(
            not isinstance(row, dict)
            or set(row) != {"version", "record_digest"}
            or row["version"] != expected[name]
            or not isinstance(row["record_digest"], str)
            or len(row["record_digest"]) != 64
            for name, row in records.items()
        )
    ):
        raise NumericalEnvironmentRefusal("prepared interpreter changed numerical identity")
    return records, version


def _installed_records(expected: Mapping[str, str]) -> dict[str, dict[str, str]]:
    records: dict[str, dict[str, str]] = {}
    for name, version in expected.items():
        distribution = importlib.metadata.distribution(name)
        record = distribution.read_text("RECORD")
        source = distribution.read_text("direct_url.json")
        if (
            distribution.version != version
            or not record
            or len(record.encode()) > 32 << 20
            or "__editable__" in record
            or (source and json.loads(source).get("dir_info", {}).get("editable"))
        ):
            raise NumericalEnvironmentRefusal("numerical platform has no immutable installed wheel")
        records[name] = {
            "version": version,
            "record_digest": _record_digest(record),
        }
    if "cozy-runtime" not in records:
        raise NumericalEnvironmentRefusal("Runtime has no installed wheel identity")
    return records


def _record_digest(record: str) -> str:
    # Installer-generated launchers contain the environment's absolute path.
    # Computation uses the wheel's importable files and native/data resources;
    # relocation, installer metadata and regenerated bytecode do not change them.
    members = []
    for row in csv.reader(io.StringIO(record)):
        if len(row) != 3:
            raise NumericalEnvironmentRefusal("numerical platform RECORD is malformed")
        path = PurePosixPath(row[0])
        if (
            path.is_absolute()
            or ".." in path.parts
            or "__pycache__" in path.parts
            or path.suffix == ".pyc"
            or row[0].endswith("/")
            or (
                len(path.parts) == 2
                and path.parts[0].endswith(".dist-info")
                and path.name
                in {"RECORD", "INSTALLER", "REQUESTED", "direct_url.json", "uv_cache.json"}
            )
        ):
            continue
        if not row[1] or not row[2]:
            raise NumericalEnvironmentRefusal("numerical platform RECORD has unhashed code")
        members.append(row)
    if not members:
        raise NumericalEnvironmentRefusal("numerical platform RECORD has no code")
    return hashlib.sha256(canonical_json.encode(sorted(members))).hexdigest()


def fingerprint(
    base: Observation,
    device: HostFacts,
    *,
    threads: int,
    alloc_conf: str,
    inherited: Mapping[str, str],
    python: Path | None = None,
) -> bytes:
    """Hash installed numerical code, measured hardware behavior, and imposed settings."""
    if device.backend == "cuda" and (device.gpu_sm <= 0 or not device.driver_version):
        raise NumericalEnvironmentRefusal("numerical device identity is unavailable")
    # Runtime's sealed child environment normally erases these. Include any
    # explicitly inherited numerical knobs, excluding access and machine identity.
    numerical = {
        key: value
        for key, value in inherited.items()
        if key.startswith(("OMP_", "MKL_", "OPENBLAS_"))
        or key
        in {
            "CUBLAS_WORKSPACE_CONFIG",
            "NVIDIA_TF32_OVERRIDE",
            "PYTHONHASHSEED",
            "CUDA_LAUNCH_BLOCKING",
            "PYTORCH_CUDA_ALLOC_CONF",
            "PYTORCH_ALLOC_CONF",
        }
    }
    records, python_version = (
        _prepared_distributions(base, python)
        if python is not None
        else (distribution_records(base), platform.python_version())
    )
    facts = {
        "interpreter": {**base.interpreter_identity, "version": python_version},
        "distributions": records,
        "torch_build": base.accelerator_build,
        "cuda_runtime": base.cuda_version,
        "device": {
            "backend": device.backend or "cpu",
            "architecture": device.gpu_sm,
            "driver": device.driver_version,
        },
        "settings": {"threads": threads, "alloc_conf": alloc_conf, "environment": numerical},
    }
    return hashlib.sha256(
        b"cozy.runtime.numerical-environment/2\0" + canonical_json.encode(facts)
    ).digest()


if __name__ == "__main__":
    try:
        payload = sys.stdin.buffer.read((64 << 10) + 1)
        expected = json.loads(payload)
        if (
            len(payload) > 64 << 10
            or not isinstance(expected, dict)
            or not expected
            or any(
                not isinstance(name, str)
                or not protected_distribution(name)
                or not isinstance(version, str)
                for name, version in expected.items()
            )
        ):
            raise NumericalEnvironmentRefusal("invalid numerical distribution roster")
        print(
            json.dumps(
                {
                    "records": _installed_records(expected),
                    "python_version": platform.python_version(),
                },
                sort_keys=True,
            )
        )
    except Exception:
        raise SystemExit("prepared interpreter numerical identity is unproven") from None
