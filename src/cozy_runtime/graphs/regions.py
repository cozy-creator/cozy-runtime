"""Shipped purity contracts for graph regions, independent of memory placement.

A region reads its arguments and its complete module subtree, writes only fresh outputs,
uses the current stream, and has no observable host effect. Successful tracing does not
establish that contract. A known container is pure only when every module under it is; unknown
code stays eager, and with it every module under it that no pure region covers.
"""

from __future__ import annotations

import functools
import inspect
import sys
from collections.abc import Collection, Iterator
from typing import Any

from cozy_runtime.internal.encoding import leaves

# Only classes generated by this Runtime may unwrap to a trusted implementation. A
# package subclass cannot inherit a marker and thereby acquire its parent's contract.
WRAPPERS: dict[type, type] = {}

#: Diffusers implementations pure once every child is, by defining module: the token-wise
#: feed-forwards, and SDXL-class UNet containers (attention through `PROCESSORS`).
DIFFUSERS = {
    "diffusers.models.activations": {
        "GELU",
        "GEGLU",
        "SwiGLU",
        "ApproximateGELU",
        "LinearActivation",
    },
    "diffusers.models.attention": {"FeedForward", "BasicTransformerBlock"},
    "diffusers.models.attention_processor": {"Attention"},
    "diffusers.models.resnet": {"ResnetBlock2D"},
    "diffusers.models.embeddings": {"Timesteps", "TimestepEmbedding"},
    "diffusers.models.unets.unet_2d_condition": {"UNet2DConditionModel"},
    "diffusers.models.downsampling": {"Downsample2D"},
    "diffusers.models.upsampling": {"Upsample2D"},
    "diffusers.models.transformers.transformer_2d": {"Transformer2DModel"},
    "diffusers.models.unets.unet_2d_blocks": {
        "DownBlock2D",
        "CrossAttnDownBlock2D",
        "UNetMidBlock2DCrossAttn",
        "CrossAttnUpBlock2D",
        "UpBlock2D",
    },
}
#: A package subclass's explicit declaration (design §5): `__cozy_graph_contract__ = Base`, a
#: contracted class it derives from, says its calls are Base's. Runtime checks that it overrides
#: nothing of Base's; it may only add.
CONTRACT = "__cozy_graph_contract__"
#: Class metadata a subclass always defines, never behaviour.
_METADATA = frozenset(
    {
        "__module__",
        "__qualname__",
        "__doc__",
        "__dict__",
        "__weakref__",
        "__annotations__",
        "__firstlineno__",
        "__static_attributes__",
        "__orig_bases__",
        "__parameters__",
        "__type_params__",
        CONTRACT,
    }
)

#: Attention processors whose call is SDPA's math through the site's shipped backend.
PROCESSORS = {
    "cozy_runtime.internal.attention": "ClassicSdpa",
    "diffusers.models.attention_processor": "AttnProcessor2_0",
}


def safe(torch: Any, module: Any) -> bool:
    """Known library implementations, with no package hooks or overwritten forwards."""
    cls = WRAPPERS.get(type(module), type(module))
    kind = _kind(torch, cls)
    if not kind or not _local(torch, module):
        return False
    if kind == "simple":
        return not getattr(module, "inplace", False)
    if kind == "native":
        return "linear" not in vars(module) and module.provider in leaves._NATIVE_OPS
    if kind == "leaf":
        forward = module._cozy_forward
        known = forward is leaves.Nvfp4NativeLeaf._forward or (
            isinstance(forward, functools.partial)
            and forward.func is leaves.MicroScaledNativeLeaf._forward
            and forward.args == (torch,)
            and not forward.keywords
        )
        return known and "linear" not in vars(module)
    if kind == "sequential":
        return all(safe(torch, child) for child in module.children())
    # Training mode alone changes none of these forwards without gradients; a dropout that
    # would act in it is refused per child (`_child`).
    return _processor(module) and all(_child(torch, child) for child in module.children())


#: A class's contract, by class, with the call path and forward it was read for.
_KINDS: dict[type, tuple[object, object, str]] = {}


def _kind(torch: Any, cls: type) -> str:
    """Which shipped contract `cls` itself meets ("" none): read once per class and forward."""
    forward, call = getattr(cls, "forward", None), cls.__call__
    known = _KINDS.get(cls)
    if known is not None and known[0] is forward and known[1] is call:
        return known[2]
    kind = ""
    module = torch.nn.Module
    own = forward is not None and forward.__qualname__ == f"{cls.__qualname__}.forward"
    if (
        call is module.__call__
        and cls._call_impl is module._call_impl
        and cls._wrapped_call_impl is module._wrapped_call_impl
    ):
        if cls in (
            torch.nn.Linear,
            torch.nn.Conv1d,
            torch.nn.Conv2d,
            torch.nn.Conv3d,
            torch.nn.LayerNorm,
            torch.nn.GroupNorm,
            torch.nn.RMSNorm,
            torch.nn.GELU,
            torch.nn.SiLU,
            torch.nn.ReLU,
        ):
            kind = "simple" if own and forward.__module__ == cls.__module__ else ""
        elif cls is leaves._native_leaf_class(torch):
            kind = "native"
        elif cls is leaves._leaf_class(torch):
            kind = "leaf"
        elif cls is torch.nn.Sequential:
            kind = "sequential"
        elif own and _declared(cls, DIFFUSERS.get(cls.__module__, ())):
            # A subclass's custom forward is excluded even when its base has this name.
            kind = "diffusers"
        elif (base := _declaration(cls)) is not None:
            kind = _kind(torch, base)
    _KINDS[cls] = (forward, call, kind)
    return kind


def _declaration(cls: type) -> type | None:
    """The contracted base a package subclass declares itself to be, when it overrides nothing
    of that base's (every class between them only adds names)."""
    base = vars(cls).get(CONTRACT)
    if not isinstance(base, type) or base is cls or not issubclass(cls, base):
        return None
    between = cls.__mro__[: cls.__mro__.index(base)]
    if any(name not in _METADATA and hasattr(base, name) for k in between for name in vars(k)):
        return None
    return base


def _local(torch: Any, sub: Any) -> bool:
    """This module alone: no instance call override, compiled call, tensor subclass, package
    hook, or package forward (Runtime's execution wrapper over the class forward is allowed).
    A weight varena has not bound yet is its placeholder: binding prepares it before replay."""
    own = sub.__dict__
    if "_call_impl" in own or "_wrapped_call_impl" in own or own.get("_compiled_call_impl"):
        return False
    for table in (sub._parameters, sub._buffers):
        for t in table.values():
            if t is not None and type(t) not in (torch.Tensor, torch.nn.Parameter, _placeholder()):
                return False
    for hooks in (sub._forward_pre_hooks, sub._forward_hooks):
        if hooks and any(
            not getattr(h, "__module__", "").startswith("tensorfs.varena.") for h in hooks.values()
        ):
            return False
    for name in ("forward", "_conv_forward"):
        forward = own.get(name)
        if forward is None:
            continue
        if forward is own.get("_cozy_execution_forward"):
            original = inspect.unwrap(forward)
            base = WRAPPERS.get(type(sub), type(sub))
            if getattr(original, "__func__", original) is base.forward:
                continue
            forward = original
        if not getattr(forward, "__module__", "").startswith("cozy_runtime.internal.execution."):
            return False
    return True


def _placeholder() -> type | None:
    return getattr(sys.modules.get("tensorfs.varena.torch"), "Placeholder", None)


def _declared(cls: type, names: Collection[str]) -> bool:
    """`cls` is the class its module defines under that name: not a same-named subclass."""
    owner = sys.modules.get(cls.__module__)
    return cls.__qualname__ in names and getattr(owner, cls.__qualname__, None) is cls


def _processor(module: Any) -> bool:
    processor = vars(module).get("processor")
    if processor is None:
        return True
    cls = type(processor)
    return (
        _declared(cls, (PROCESSORS.get(cls.__module__, ""),))
        and getattr(processor, "_parallel_config", None) is None
    )


def _child(torch: Any, module: Any) -> bool:
    cls = WRAPPERS.get(type(module), type(module))
    if cls is torch.nn.Dropout:
        return _local(torch, module) and (not module.training or module.p == 0)
    if cls in (torch.nn.ModuleList, torch.nn.ModuleDict):
        return _local(torch, module) and all(_child(torch, c) for c in module.children())
    return safe(torch, module)


def regions(torch: Any, root: Any, path: str = "") -> Iterator[tuple[str, Any]]:
    """Largest declared-safe subtrees of a root with no declared blocks."""
    if safe(torch, root):
        yield path, root
    else:
        for name, child in root.named_children():
            yield from regions(torch, child, f"{path}.{name}" if path else name)


def segments(torch: Any, root: Any, blocks: Collection[str]) -> Iterator[tuple[str, Any]]:
    """Pure subtrees holding at least one declared block, coarsest first, each followed by the
    finer ones under it: one that cannot be prepared runs eager and its finer ones replay. A
    block no pure region covers runs eager whole; no single op becomes a region of its own."""

    def walk(module: Any, path: str) -> Iterator[tuple[str, Any]]:
        if path and not any(b == path or b.startswith(path + ".") for b in blocks):
            return
        if safe(torch, module):
            yield path, module
        for name, child in module.named_children():
            yield from walk(child, f"{path}.{name}" if path else name)

    yield from walk(root, "")
